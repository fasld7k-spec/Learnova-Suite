export function localizedPageCopy(locale?: string | null): PageCopy {
  const normalized = normalizeLocale(locale);
  const base = pageCopyByLocale[normalized === 'ar' ? 'ar' : 'en'];
  const patch = overrides[normalized];
  return (patch ? { ...base, ...patch } : base) as PageCopy;
}
