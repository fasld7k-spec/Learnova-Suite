/**
 * lib/payment-gateways/base.ts
 *
 * Shared TypeScript types and the GatewayAdapter interface used by every
 * payment-gateway implementation in Learnova Suite.
 *
 * All gateway adapters MUST implement GatewayAdapter so that the webhook
 * router, checkout flow, and refund handler can work with any gateway
 * through a single, uniform contract.
 */

// ---------------------------------------------------------------------------
// Shared domain types
// ---------------------------------------------------------------------------

/**
 * A lightweight representation of an Order as needed by gateway adapters.
 * Mirrors the Prisma Order model but uses plain TypeScript types so adapters
 * remain decoupled from the ORM layer.
 */
export interface Order {
  id: string;
  userId: string;
  /** Numeric total in the order's currency (e.g. 49.99). */
  total: number;
  currency: string;
  status: OrderStatus;
  gateway: string;
  invoiceNumber: string;
  items: OrderItem[];
  createdAt: Date;
}

export type OrderStatus = 'PENDING' | 'PAID' | 'FAILED' | 'REFUNDED' | 'CANCELLED';

/** A single line item within an Order. */
export interface OrderItem {
  id: string;
  courseId: string;
  title: string;
  price: number;
}

// ---------------------------------------------------------------------------
// Session creation
// ---------------------------------------------------------------------------

/** Options passed to GatewayAdapter.createSession. */
export interface SessionOptions {
  /** Absolute URL the gateway should redirect to after a successful payment. */
  successUrl: string;
  /** Absolute URL the gateway should redirect to when the user cancels. */
  cancelUrl: string;
  /**
   * An opaque reference string generated by the caller (e.g.
   * `RAZORPAY-INV-001-1716000000000`) used to correlate gateway events back
   * to the internal order.
   */
  reference: string;
  /** Locale hint for gateways that support localised checkout pages. */
  locale?: string;
  /** Any extra gateway-specific parameters the caller wants to forward. */
  metadata?: Record<string, string | number | boolean>;
}

/**
 * The result returned by GatewayAdapter.createSession.
 *
 * - `redirect` — the student should be sent to `redirectUrl`.
 * - `inline`   — the gateway renders a widget/form in-place (e.g. Iyzico,
 *                HyperPay); `payload` carries the data needed to mount it.
 * - `free`     — zero-value order; no external gateway interaction required.
 * - `offline`  — manual / bank-transfer; `instructions` guides the student.
 */
export interface PaymentSession {
  /** The normalised gateway slug (e.g. `"razorpay"`). */
  gateway: string;
  /** Internal order ID. */
  orderId: string;
  /** The opaque reference string echoed from SessionOptions. */
  reference: string;
  /** How the checkout should be presented to the student. */
  mode: 'redirect' | 'inline' | 'free' | 'offline';
  /**
   * The provider-assigned session / order / charge identifier.
   * Used later in capturePayment and for idempotency checks.
   */
  providerSessionId: string;
  /**
   * Present when mode is `redirect` or `offline`.
   * For `redirect` this is the hosted checkout URL.
   * For `offline` this is the manual-payment instructions page URL.
   */
  redirectUrl?: string;
  /** Human-readable instructions shown to the student (offline / inline). */
  instructions?: string;
  /**
   * Arbitrary gateway-specific data (e.g. the Iyzico form token or the
   * HyperPay checkout ID) needed to mount an inline widget.
   */
  payload?: Record<string, unknown>;
}

// ---------------------------------------------------------------------------
// Capture
// ---------------------------------------------------------------------------

/** The result returned by GatewayAdapter.capturePayment. */
export interface CaptureResult {
  /** Whether the capture succeeded. */
  success: boolean;
  /**
   * The gateway's transaction / capture identifier.
   * Stored on the Payment record for reconciliation.
   */
  transactionId: string;
  /** The captured amount in the order's currency. */
  amount: number;
  currency: string;
  /** Raw response data from the gateway API (for audit / debugging). */
  rawResponse?: Record<string, unknown>;
}

// ---------------------------------------------------------------------------
// Refund
// ---------------------------------------------------------------------------

/** The result returned by GatewayAdapter.refundPayment. */
export interface RefundResult {
  /** Whether the refund was accepted by the gateway. */
  success: boolean;
  /**
   * The gateway's refund identifier.
   * Stored on the Payment record for reconciliation.
   */
  refundId: string;
  /** The refunded amount in the order's currency. */
  amount: number;
  currency: string;
  /** Raw response data from the gateway API (for audit / debugging). */
  rawResponse?: Record<string, unknown>;
}

// ---------------------------------------------------------------------------
// Structured error type
// ---------------------------------------------------------------------------

/**
 * Returned (not thrown) by adapter methods when a gateway API call fails.
 * Requirement 1.15: adapters MUST log the error with full context and return
 * a structured error response rather than letting an unhandled exception
 * propagate.
 */
export interface GatewayError {
  /** Always `false` — allows callers to discriminate from success results. */
  success: false;
  /** Short machine-readable error code (e.g. `"NETWORK_ERROR"`). */
  code: string;
  /** Human-readable description of what went wrong. */
  message: string;
  /** HTTP status returned by the gateway, if applicable. */
  httpStatus?: number;
  /** Raw error payload from the gateway for debugging. */
  rawResponse?: Record<string, unknown>;
}

// ---------------------------------------------------------------------------
// GatewayAdapter interface
// ---------------------------------------------------------------------------

/**
 * Every payment-gateway implementation MUST implement this interface.
 *
 * Requirement 1.1: The Payment_Gateway SHALL implement the GatewayAdapter
 * interface with `createSession`, `verifyWebhook`, `capturePayment`, and
 * `refundPayment` methods for each supported gateway.
 */
export interface GatewayAdapter {
  /**
   * Create a checkout session with the external gateway.
   *
   * @param order   - The internal order to be paid.
   * @param options - URLs, reference string, and optional metadata.
   * @returns A PaymentSession describing how to present the checkout, or a
   *          GatewayError if the API call failed.
   */
  createSession(
    order: Order,
    options: SessionOptions,
  ): Promise<PaymentSession | GatewayError>;

  /**
   * Verify the authenticity of an incoming webhook request.
   *
   * The raw request body MUST be passed as a string (before any JSON
   * parsing) so that HMAC signatures can be computed correctly.
   *
   * @param payload   - Raw request body string.
   * @param signature - The signature header value sent by the gateway.
   * @returns `true` if the signature is valid, `false` otherwise.
   *
   * Requirement 2.8: returning `false` MUST cause the webhook route to
   * respond with HTTP 401 and skip all event processing.
   */
  verifyWebhook(payload: string, signature: string): boolean;

  /**
   * Capture (confirm) a previously authorised payment.
   *
   * @param sessionId - The `providerSessionId` from the PaymentSession.
   * @returns A CaptureResult on success, or a GatewayError on failure.
   */
  capturePayment(
    sessionId: string,
  ): Promise<CaptureResult | GatewayError>;

  /**
   * Issue a full or partial refund for a completed transaction.
   *
   * @param transactionId - The gateway transaction / capture ID to refund.
   * @param amount        - Amount to refund in the order's currency.
   * @returns A RefundResult on success, or a GatewayError on failure.
   *
   * Requirement 1.14: on success the caller MUST update the Order status
   * to `REFUNDED`.
   */
  refundPayment(
    transactionId: string,
    amount: number,
  ): Promise<RefundResult | GatewayError>;
}

// ---------------------------------------------------------------------------
// Type guard helpers
// ---------------------------------------------------------------------------

/** Returns `true` when the value is a GatewayError (i.e. the call failed). */
export function isGatewayError(
  result: PaymentSession | CaptureResult | RefundResult | GatewayError,
): result is GatewayError {
  return (result as GatewayError).success === false;
}
