  // --- new fields for expanded token architecture ---
  accentSoftColor: string;        // --home-accent-soft: low-opacity tint of accent
  surfaceAltColor: string;        // --home-surface-alt: secondary surface (e.g. card hover bg)
  fontFamily: string;             // --home-font-family: body text font stack
  fontDisplay: string;            // --home-font-display: heading/display font stack
  radius: string;                 // --home-radius: base border-radius for interactive elements
  radiusCard: string;             // --home-radius-card: border-radius for card components
