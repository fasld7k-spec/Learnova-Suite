export type HomeThemeId = typeof homeThemeRegistry[number]['id'];

export const defaultHomeThemeId = 'theme-7' as HomeThemeId;
export const homeThemeIds = homeThemeRegistry.map((theme) => theme.id) as HomeThemeId[];
export const defaultHomeThemes = Object.fromEntries(homeThemeRegistry.map((theme) => [theme.id, theme.defaults])) as unknown as Record<HomeThemeId, HomeThemeSettings>;
export const homeThemeCopyFields = Array.from(
  new Set(homeThemeRegistry.flatMap((theme) => Object.keys(theme.defaults))),
) as (keyof HomeThemeSettings)[];

export function isHomeThemeId(value: unknown): value is HomeThemeId {
  return typeof value === 'string' && homeThemeIds.includes(value as HomeThemeId);
}

export function parseHomeThemeId(value: unknown, fallback: HomeThemeId = defaultHomeThemeId): HomeThemeId {
  return isHomeThemeId(value) ? value : fallback;
}

export function getHomeThemeDefinition(id: HomeThemeId) {
  return homeThemeRegistry.find((theme) => theme.id === id) || homeThemeRegistry[0];
}


